export const summarizeStrength = (questionText: string, diff: number): string => {
  const rule = findRule(questionText)
  if (rule) {
    return diff === 0 ? rule.messages.strength[0] : rule.messages.strength[1]
  }
  const topic = cleanForTopic(questionText)
  return diff === 0
    ? `${topic}${SEPARATOR}두 분 기준이 딱 같아요. 이 부분은 걱정 없어요.`
    : `${topic}${SEPARATOR}비슷한 편이에요. 큰 갈등 없이 맞춰갈 수 있어요.`
}

export const summarizeCaution = (questionText: string, diff: number): string => {
  const rule = findRule(questionText)
  if (rule) {
    return diff >= 3 ? rule.messages.caution[1] : rule.messages.caution[0]
  }
  const topic = cleanForTopic(questionText)
  return diff >= 3
    ? `${topic}${SEPARATOR}차이가 꽤 커요. 미리 대화로 기준을 맞춰두면 좋아요.`
    : `${topic}${SEPARATOR}살짝 차이가 있어요. 한 번쯤 서로 이야기해보세요.`
}

// For the Pro Top-5 conflict cards — shorter label only, AI advice follows below.
export const summarizeConflict = (questionText: string, diff: number): string => {
  const topic = cleanForTopic(questionText)
  if (diff >= 3) return `${topic}${SEPARATOR}답이 꽤 달라요`
  if (diff >= 2) return `${topic}${SEPARATOR}답이 살짝 달라요`
  return `${topic}${SEPARATOR}가벼운 차이가 있어요`
}

