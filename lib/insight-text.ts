const findRule = (questionText: string): TopicRule | null => {
  for (const rule of TOPIC_RULES) {
    if (rule.keywords.some(k => questionText.includes(k))) return rule
  }
  return null
}

const QUESTION_END = /[?？!]+\s*$/
const TAIL_REPLACEMENTS: [RegExp, string][] = [
  [/(은|는|이|가)\s*보통\s*얼마나\s*자주\s*하세요?\s*$/u, ''],
  [/(은|는|이|가)\s*보통\s*얼마나\s*자주\s*하나요?\s*$/u, ''],
  [/(은|는|이|가)\s*어때요?\s*$/u, ''],
  [/(은|는|이|가)\s*어떠세요?\s*$/u, ''],
  [/(은|는|이|가)\s*어떻게\s*되세요?\s*$/u, ''],
  [/(.+)는\s*거\s*어때요?\s*$/u, '$1는 것'],
  [/얼마나\s*자주\s*(해요|하세요|하나요)?\s*$/u, ''],
  [/언제\s*(해요|하세요)?\s*$/u, ''],
  [/(있어요|있나요|있으세요)\s*$/u, ''],
  [/(되세요|하세요|드세요|쓰세요|보세요)\s*$/u, ''],
]
const stripTopicMarker = (t: string) => t.replace(/(은|는|이|가)\s*$/u, '').replace(/\s+$/u, '')

const cleanForTopic = (raw: string): string => {
  let t = raw.trim().replace(QUESTION_END, '').trim()
  for (const [re, rep] of TAIL_REPLACEMENTS) t = t.replace(re, rep).trim()
  return stripTopicMarker(t)
}

